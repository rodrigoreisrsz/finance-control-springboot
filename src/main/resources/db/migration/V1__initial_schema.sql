CREATE TABLE usuario (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255),
    password VARCHAR(255) NOT NULL,
    CONSTRAINT uk_usuario_email UNIQUE (email)
);

CREATE TABLE registro (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    nome VARCHAR(255),
    valor NUMERIC(38, 2),
    descricao VARCHAR(255),
    data DATE,
    tipo_registro VARCHAR(255),
    CONSTRAINT fk_registro_usuario FOREIGN KEY (user_id) REFERENCES usuario (user_id)
);

CREATE TABLE saldo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT UNIQUE,
    saldo NUMERIC(38, 2),
    CONSTRAINT fk_saldo_usuario FOREIGN KEY (user_id) REFERENCES usuario (user_id)
);

CREATE TABLE cofre (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    nome VARCHAR(255),
    meta NUMERIC(38, 2),
    CONSTRAINT fk_cofre_usuario FOREIGN KEY (user_id) REFERENCES usuario (user_id)
);

CREATE TABLE aporte (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cofre_id BIGINT,
    valor NUMERIC(38, 2),
    data DATE,
    CONSTRAINT fk_aporte_cofre FOREIGN KEY (cofre_id) REFERENCES cofre (id)
);

CREATE INDEX idx_registro_user_id ON registro (user_id);
CREATE INDEX idx_cofre_user_id ON cofre (user_id);
CREATE INDEX idx_aporte_cofre_id ON aporte (cofre_id);
