ALTER TABLE registro
    ADD COLUMN categoria VARCHAR(32);

CREATE TABLE orcamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    categoria VARCHAR(32) NOT NULL,
    valor NUMERIC(12, 2) NOT NULL,
    mes DATE NOT NULL,
    CONSTRAINT fk_orcamento_usuario FOREIGN KEY (user_id) REFERENCES usuario (user_id),
    CONSTRAINT uk_orcamento_user_categoria_mes UNIQUE (user_id, categoria, mes)
);

CREATE TABLE recorrencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    nome VARCHAR(100) NOT NULL,
    valor NUMERIC(12, 2) NOT NULL,
    descricao VARCHAR(300),
    tipo_registro VARCHAR(16) NOT NULL,
    categoria VARCHAR(32) NOT NULL,
    dia_do_mes INTEGER NOT NULL,
    data_inicio DATE NOT NULL,
    proxima_execucao DATE NOT NULL,
    ativa BOOLEAN NOT NULL,
    confirmacao_obrigatoria BOOLEAN NOT NULL,
    CONSTRAINT fk_recorrencia_usuario FOREIGN KEY (user_id) REFERENCES usuario (user_id)
);

CREATE INDEX idx_orcamento_user_mes ON orcamento (user_id, mes);
CREATE INDEX idx_recorrencia_vencimento
    ON recorrencia (ativa, confirmacao_obrigatoria, proxima_execucao);
